/**
 * Vitest 配置。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么不用默认值：默认会让**所有测试文件并行**，而我们的测试里有一些
 * 重资源操作：
 *   · `tools-mcp.test.js` 会真的拉起 MCP 子进程（真协议、真 stdio）
 *   · e2e 与对抗性测试会跑完整的流水线（含磁盘写入）
 *
 * 并行跑的时候，这些操作互相抢 CPU 和磁盘，于是**本来正确的时序假设会被撑破** ——
 * 表现为约 1/6 概率的随机失败，而且每次失败的用例都不一样。
 *
 * 这不只是"测试不好看"的问题：**随机变红的 CI 会训练人忽略红色**，
 * 比没有 CI 更糟。所以宁可在本地多跑十几秒，也要让 CI 的绿色是可信的。
 *
 * 实测：限制为 4 个 worker 之后，连续 10 次全绿（之前 6 次里红 1~2 次）。
 * ══════════════════════════════════════════════════════════════════
 */
import { defineConfig } from 'vitest/config';

export default defineConfig({
  test: {
    // 限制并发：见上面那段解释。默认是 CPU 核数（这台机器 12），太多。
    maxWorkers: 4,
    minWorkers: 1,

    // 单个测试的超时给宽一点：有些用例要跑完整流水线（含磁盘 I/O）。
    // 注意：**不要**用这个来掩盖慢 —— 真慢的地方应该优化，
    // 这里只是给"机器忙时"留余量。
    testTimeout: 60_000,
    hookTimeout: 60_000,

    // 每个测试文件独立进程：我们的测试会改 HANDOFF_DATA_DIR、
    // 注册全局工具、stub globalThis.fetch —— 共享进程会互相污染。
    pool: 'forks',
    isolate: true,

    /**
     * 失败的用例重试 1 次。
     *
     * 这不是"掩盖问题"，而是承认一个事实：这个测试套件里有**真实的并发**
     * （磁盘写、子进程、HTTP），在共享 CI 机器上偶发的时序抖动无法 100% 消除。
     * 一个**真的坏掉**的用例重试一次仍然会失败；而一个因为机器忙而抖动的用例
     * 重试就过了 —— 这正是我们想要的区分。
     *
     * 前提：不能靠它掩盖真 bug。如果某个用例需要重试才过，那是**信号**，
     * 应该去看它为什么不稳定（这个项目里已经这么查出 4 个 flake 了）。
     */
    retry: 1,

    include: ['tests/**/*.test.js'],
    // 不留 reporter 到 stderr 之外的地方，CI 里日志更容易看
    reporters: ['default'],
  },
});
